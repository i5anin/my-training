/**
 * Подробная инструкция к упражнению. Данные подобраны под ограничение
 * по позвоночнику (ДДЗП): поясница в опоре или в нейтрали, без осевого
 * сжатия и переразгибания.
 */
export interface Technique {
  /** Эмодзи-маркер карточки */
  icon: string;
  /** Настройка снаряда до начала: высота, углы, положение блока */
  setup: string[];
  /** Исходное положение перед первым повтором */
  start: string[];
  /** Само движение по шагам, в порядке выполнения */
  steps: string[];
  /** Дыхание */
  breathing: string;
  /** Что должно работать и ощущаться — контроль по чувствам */
  feel: string;
  /** Разминочные подходы перед рабочими */
  warmup: string;
  /** Типичные ошибки */
  mistakes: string[];
  /** Как понять, что вес подобран верно */
  check: string;
  /** Когда и на сколько добавлять */
  progression: string;
  /** Замечание по спине; пусто, если упражнение нейтрально */
  spine?: string;
  tempo: string;
  rest: string;
}
